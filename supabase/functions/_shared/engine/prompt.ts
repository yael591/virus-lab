export const ZOOM_FIELD_HE: Record<string, string> = {
  first_name: 'שם פרטי של המטופל',
  last_name: 'שם משפחה של המטופל',
  national_id: 'תעודת זהות של המטופל (בדיוק כפי שכתובה, כולל אפסים מובילים)',
  central_numbers: 'מספר מרכזי — 6 ספרות (ייתכנו כמה)',
  received_date: 'תאריך קבלה (כפי שכתוב, למשל 27.8.26)',
};

export interface RereadItem {
  key: string;
  field: string;
}

export function buildRereadPrompt(items: RereadItem[], sender: string | null = null): string {
  const hasCommitment = items.some((it) => it.field === 'commitment_number');
  const senderBlock = hasCommitment
    ? `\nגורם שולח של הטופס: ${sender ?? 'לא ידוע'}.\n${FORM_HINTS}\n`
    : '';
  const label = (f: string) => (f === 'commitment_number' ? 'מספר התחייבות (מזהה הקופה/בית החולים; ייתכנו אות X בתחילתו)' : ZOOM_FIELD_HE[f] ?? f);
  const shape = (f: string) => (f === 'central_numbers' ? '[{"value": "...", "confidence": 0.0, "quote": "..."}]' : '{"value": "...", "confidence": 0.0, "quote": "..."}');
  return `כל תמונה מצורפת היא הגדלה של אזור קטן מטופס התחייבות רפואי, ולפניה כתוב איזה מפתח היא שייכת אליו ומה השדה.
קראי את השדה מתוך ההגדלה, ספרה אחרי ספרה ואות אחרי אות.
- קראי לפי צורות האותיות והספרות שרואים. אסור להמציא ערך שלא דומה לכתוב.
- שם בכתב יד רהוט: החזירי את הקריאה הטובה ביותר כהצעה, עם confidence לכל היותר 0.5 (הבודקת תאשר). null רק אם לא נראית אף אות.
- מספרים: ספרה לא ודאית → confidence נמוך; לא להשלים ספרות חסרות. בלבולים נפוצים בכתב יד: 1↔7, 4↔9, 0↔6, 3↔8, 5↔6.
- אם בהגדלה יש כמה מספרים, בחרי את זה שמתאים לשדה המבוקש (לפי התווית שלידו), לא מספר אחר.
- אם בשדה "שם" אחד מופיעים שם פרטי ושם משפחה — שם המשפחה בדרך כלל ראשון.
- מספר התחייבות מתוך גזירות ממוספרות: בחרי את המספר שמתאים לגורם השולח לפי הרמזים למטה (תווית, מיקום, מדבקה, עמודה בטבלה).
  אסור לבחור מספר מקרה, ביקור, קבלה, תיק, טלפון, ת.ז. או מספר מרכזי. ציני ב-quote את מספר הגזירה. אם אף אחד לא מתאים: null.
- הגדלה שבנויה מכמה גזירות ממוספרות (1, 2, 3...) עם מספר בצד = מועמדים מאותו עמוד: אזורים שבהם יש כתב יד.
  מצאי ביניהם את שם המטופל (לא רופא, מחלקה, מוסד, חתימה או תאריך) וקראי אותו. ציני ב-quote את מספר הגזירה. אם אף גזירה אינה שם מטופל: null.
- הגדלה שמחולקת בקו אפור לשני חלקים = אותו אזור בשני סיבובים (90° ו-270°), כי הטקסט נכתב בצד. קראי מהחלק שבו הכתב ישר; אל תחברי בין שני החלקים.
${senderBlock}
החזירי JSON בלבד, עם המפתחות האלה בדיוק:
{${items.map((it) => `"${it.key}": ${shape(it.field)}`).join(', ')}}

המפתחות: ${items.map((it) => `${it.key} = ${label(it.field)}`).join(' · ')}`;
}
