export function buildUserText(ocrText: string, hints: RegexHints, hasZoom = false): string {
  const hintLines: string[] = [];
  if (hints.senderGuess) hintLines.push(`גורם שולח משוער: ${hints.senderGuess}`);
  if (hints.commitmentCandidates.length) hintLines.push(`מועמדים למספר התחייבות: ${hints.commitmentCandidates.join(', ')}`);
  if (hints.centralCandidates.length) hintLines.push(`מועמדים למספר מרכזי: ${hints.centralCandidates.join(', ')}`);
  return `חלצי את השדות מהעמוד המצורף.${hasZoom ? ' (התמונה הראשונה היא העמוד המלא; האחרות הן הגדלות של אותו עמוד.)' : ''}

${hintLines.length ? `ממצאי חיפוש דטרמיניסטי בטקסט (אמינים לטקסט מודפס; אמתי מול התמונה):\n${hintLines.join('\n')}\n` : ''}
טקסט OCR של העמוד (עלול להכיל שגיאות, במיוחד בכתב יד — התמונה היא המקור הקובע):
<<<OCR
${(ocrText ?? '').slice(0, 6000)}
OCR>>>`;
}

